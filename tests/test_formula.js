/* test_formula.js: 式で作る列の計算(§9.111 ⑦)
   ============================================================
   要望は「計算式で条件を追加できるが、元の列が無いと使えない」。
   つまり**データ側に無い列を、既にある列から作りたい**。

   ここはブラウザを使わない(式の意味だけを見るので、画面は要らない)。
   固定するのは、間違えると黙って変な値が出る種類のもの。
    1. `eval`を使っていない——式はマスタに保存され他のPCでも動く。
       文字列をJSとして実行する作りだと、保存した式が何でもできてしまう
    2. `+` は数どうしなら足し算、片方が文字なら連結
    3. 比較は**数どうしのときだけ数で**比べる（'010' と 10 を同じにしない）
    4. 壊れた式・知らない関数は**書いている時点で**断る
    5. 0除算・無い列は空にする（例外で列ごと落とさない）
   ============================================================ */
const path=require('path');
global.window={};
require(path.join(__dirname,'..','static','js','list-formula.js'));
const F=global.window.WL.formula;

const R=[];
const rec=(n,ok,d)=>{R.push({n,ok,d});console.log((ok?'PASS':'FAIL')+': '+n+(d?' -- '+d:''))};

const row={'ロット番号':'L0001','板厚':'2.5','幅':'1200','数量':'10',
           '材質':'A5052','空欄':'','ゼロ':'0','コード':'010'};
const val=src=>F.compile(src).run(row);
/* 「値が作れない」は null で返し、画面側が空文字にする。テストでは
   どちらも「空」として同じに扱う(内部の型の違いを固定しても意味が無い)。 */
const same=(a,b)=>{
 const norm=v=>(v===null||v===undefined)?'':String(v);
 return norm(a)===norm(b);
};
const ok=(src,want,note)=>{
 const c=F.check(src);
 if(!c.ok){rec(note||src,false,'式が通らない: '+c.error);return}
 const got=val(src);
 rec(note||src,same(got,want),`=> ${JSON.stringify(got)}${same(got,want)?'':' / 期待 '+JSON.stringify(want)}`);
};

/* ---- 1) evalを使っていない ---- */
// **これが崩れると、保存した式が他のPCで何でもできてしまう。**
const src=require('fs').readFileSync(path.join(__dirname,'..','static','js','list-formula.js'),'utf8');
rec('evalもFunction生成も使っていない',
 !/\beval\s*\(/.test(src)&&!/new\s+Function\s*\(/.test(src));
// 実際にJSの式として書いても通らないことを見る(構文が別物であること)
rec('JSの式は通らない(1)',!F.check('process.exit(1)').ok,F.check('process.exit(1)').error);
rec('JSの式は通らない(2)',!F.check('[材質].constructor').ok);
rec('文字列からの関数呼び出しは通らない',!F.check('alert("x")').ok);

/* ---- 2) 四則と連結 ---- */
ok('[数量] + 5',15);
ok('[数量] - 3',7);
ok('[幅] * 2',2400);
ok('[幅] / 4',300);
ok('[数量] % 3',1);
ok('[板厚] * [幅]',3000);
ok('[ロット番号] + "-A"','L0001-A','+ は片方が文字なら連結');
ok('"合計:" + [数量]','合計:10');
ok('-[数量]',-10);
ok('([数量] + 2) * 3',36,'かっこが効く');

/* ---- 3) 比較 ---- */
ok('[数量] > 5',1);
ok('[数量] < 5',0);
ok('[材質] = "A5052"',1);
ok('[材質] <> "A5052"',0);
ok('[コード] = "010"',1,'文字は文字のまま比べる');
ok('[コード] = 10',0,'文字と数を同じにしない（010 と 10）');
ok('[板厚] = 2.5',1,'ふつうの数はちゃんと数として比べる');
ok('[数量] = "10"',1,'見た目どおりの数どうしは一致する');
ok('[数量] >= 10',1);

/* ---- 4) 論理と分岐 ---- */
ok('[数量] > 5 and [幅] > 1000',1);
ok('[数量] > 50 or [幅] > 1000',1);
ok('not([数量] > 50)',1);
ok('if([数量] > 5, "多い", "少ない")','多い');
ok('if([数量] > 50, "多い", "少ない")','少ない');
ok('if([数量] > 50, "多い")','','ifの3つ目は省略できる');

/* ---- 5) 関数 ---- */
ok('round([板厚] / 3, 2)',0.83);
ok('abs(0 - [数量])',10);
ok('len([ロット番号])',5);
ok('left([ロット番号], 2)','L0');
ok('right([ロット番号], 2)','01');
ok('upper([材質])','A5052');
ok('lower("ABC")','abc');
ok('trim("  x  ")','x');
ok('concat([材質], "/", [板厚])','A5052/2.5');
ok('coalesce([空欄], [材質])','A5052','空欄は飛ばして次を使う');
ok('num("1,200")',1200,'桁区切りのある文字も数として読む');

/* ---- 6) 壊れた式は「書いている時点で」断る ---- */
// 実データの行が全部空になってから気づくのでは遅い。
[['[未閉じ','列名の [ ] が閉じていません'],
 ['1 +','式が途中で終わっています'],
 ['foo()','知らない関数'],
 ['round(1)','引数'],
 ['left(1,2,3)','引数'],
 ['if(1)','if は'],
 ['1 ) 2','余分'],
 ['"abc','引用符'],
 ['@@@','使えない文字']].forEach(([bad,part])=>{
  const r=F.check(bad);
  rec(`壊れた式を断る: ${bad}`,!r.ok&&String(r.error).includes(part),r.error||'通ってしまった');
 });
rec('空の式は「使える」と言わない',!F.check('   ').ok);

/* ---- 7) 値が作れないときは空にする(例外にしない) ---- */
ok('[数量] / 0','','0で割ったら空');
ok('[無い列]','','無い列は空');
ok('[無い列] + 1','1','無い列との連結は残りだけ');
ok('[空欄] * 2','','空欄の計算は空');

/* ---- 8) 使っている列が分かる(説明と取得漏れの確認に使う) ---- */
const used=F.check('[幅] * [板厚] + len([ロット番号])').columns;
rec('式に出てくる列を拾える',
 ['幅','板厚','ロット番号'].every(k=>used.includes(k))&&used.length===3,JSON.stringify(used));

/* ---- 9) 長すぎる式は入口で断る ---- */
rec('長すぎる式は断る',!F.check('1+'.repeat(300)+'1').ok);

const ng=R.filter(x=>!x.ok);
console.log(`\n=== SUMMARY ===\n${R.length-ng.length}/${R.length} passed`);
ng.forEach(x=>console.log(' -',x.n,x.d||''));
process.exit(ng.length?1:0);
