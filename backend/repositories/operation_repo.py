def builtin_choice_name(c, key):
    """組み込みの欄がどのまとまりから選ぶか(§9.221 ③)。**マスタの
    `[選択肢名]`が答える**——移行で既定を張ってあるが、現場が別のまとまりへ
    向け替えられる（それが「汎用化」の意味）。行が無い・空のときだけ既定へ
    落ちる。**測定画面はここを通す**——名前をコードへ書くと、画面から
    向け替えても効かない設定になる。"""
    fallback = dict((k, g) for g, k in LEGACY_CHOICE_GROUPS).get(str(key or ''), '')
    try:
        for it in item_rows(c, True):
            if it['builtin'] == key:
                return it['choice'] or fallback
    except Exception:
        pass
    return fallback


def choice_used_bump(c, name, value, n=1):
    """選ばれた回数を1つ増やす（§9.248 ⑤）。**無ければ何もしない**
    ——手で打った値（選択肢に無い値）まで行を作ると、マスタが打ち間違いで
    膨れる（§9.226 ①「手打ちの値は選択肢マスタへ足さない」）。"""
    nm = str(name or '').strip()
    v = str(value or '')
    if not nm or not v:
        return 0
    try:
        ensure_choice_table(c)
    except Exception:
        return 0
    cur = c.cursor()
    cur.execute(f'UPDATE [{CHOICE_TABLE}] '
                'SET [使用回数]=COALESCE([使用回数],0)+? '
                'WHERE [選択肢名]=? AND [値]=?', [int(n), nm, v])
    c.commit()
    return cur.rowcount


# ---------------------------------------------------------------------------
# 選択肢リンクマスタ（§9.306、利用者の指示）
# ---------------------------------------------------------------------------
# 「選択肢の値マスタ同士を親子関係として紐づけるためにリンクさせ、リンク
#  させた場合、子となったマスタは登録内容毎、どの親か親マスタから選ぶことが
#  できるようにしたい」
#
# **1行＝1つの親子**（親のまとまり → 子のまとまり）。**子で一意**——子の
# まとまりに親が2つあると「どちらの欄で絞るのか」が決まらない（§9.239 ⑥の
# 1ロール1設備と同じ理由で、索引で構造として止める）。
#
# **1段だけ**（利用者の指示）。あるまとまりが**親と子を兼ねられない**ように
# 断ることで、孫が構造として作れなくなる——「1段だけ」を後から画面の判定で
# 守ろうとすると、既に保存された2段を読んだときの振る舞いが決まらない。
#
# **どの値がどの親に属すかは選択肢の値の`[親の値]`**。空欄＝どの親でも出るので、
# リンクを張っただけでは候補は1つも減らない（§9.132。絞りたい値にだけ
# 親の値を入れていけば、途中の状態でも現場が止まらない）。
CHOICE_LINK_TABLE = '選択肢リンクマスタ'


def ensure_choice_link_table(c):
    if CHOICE_LINK_TABLE not in tables(c):
        cur = c.cursor()
        cur.execute('CREATE TABLE [選択肢リンクマスタ] ('
                    '[リンクID] INTEGER PRIMARY KEY AUTOINCREMENT, '
                    '[親まとまり] TEXT, [子まとまり] TEXT, [説明] TEXT, [有効] INTEGER, '
                    '[登録者ID] TEXT, [更新者ID] TEXT, [登録日時] DATETIME, [更新日時] DATETIME)')
        # **子で一意**——1つの子に親は1つ。
        cur.execute('CREATE UNIQUE INDEX [UX_選択肢リンクマスタ_子] '
                    'ON [選択肢リンクマスタ] ([子まとまり])')
        c.commit()
        return True
    return False


def choice_links(c, include_disabled=False):
    """**読み取り専用の接続からも読めること**（§9.221 ③）——測定画面は
    `connect(path,True)`で開く。表が無ければ空。"""
    try:
        ensure_choice_link_table(c)
    except Exception:
        pass
    if CHOICE_LINK_TABLE not in tables(c):
        return []
    cur = c.cursor()
    try:
        cur.execute('SELECT [リンクID],[親まとまり],[子まとまり],[説明],[有効] '
                    'FROM [選択肢リンクマスタ] ORDER BY [親まとまり],[子まとまり]')
        raw = cur.fetchall()
    except Exception:
        return []
    out = []
    for r in raw:
        on = True if r[4] is None else bool(r[4])
        if not on and not include_disabled:
            continue
        parent = str(r[1] or '').strip()
        child = str(r[2] or '').strip()
        if not parent or not child:
            continue
        out.append({'id': r[0], 'parent': parent, 'child': child,
                    'note': str(r[3] or ''), 'enabled': on})
    return out


def choice_parent_of(c, child_name):
    """その子のまとまりの**親のまとまり名**（無ければ空）。
    **判定はここ1箇所**（§9.163）——画面もサーバーもこの答えを見る。"""
    n = str(child_name or '').strip()
    if not n:
        return ''
    for link in choice_links(c):
        if link['child'] == n:
            return link['parent']
    return ''


def choice_children_of(c, parent_name):
    n = str(parent_name or '').strip()
    return [x['child'] for x in choice_links(c) if n and x['parent'] == n]


def choice_matches_parent(stored, parent_value):
    """その値が**この親の値のときに出るか**。**空欄は「すべての親」**
    （`choice_matches_equipment`と同じ約束——同じ意味の判定を2通り書かない）。"""
    from . import schedule_repo as sr
    if not str(stored or '').strip():
        return True
    return sr.stop_equipment_matches(stored, parent_value)


def choice_link_upsert(c, parent, child, uid, note=None, enabled=None, link_id=None):
    """親子を1本張る。**断るときは理由と打つ手を返す**（§4）。"""
    ensure_choice_link_table(c)
    p = str(parent or '').strip()
    ch = str(child or '').strip()
    if not p or not ch:
        raise ValueError('親と子のまとまりを両方選んでください。')
    if p == ch:
        raise ValueError('同じまとまりを親と子にはできません（自分で自分を絞ることになります）。')
    names = set(choice_names(c))
    for n in (p, ch):
        if n not in names:
            raise ValueError(f'「{n}」という選択肢のまとまりがありません'
                             '（マスタ管理 > 測定と記録 > 選択肢の値 で作ってください）。')
    # **1段だけ**（利用者の指示）。親と子を兼ねられないようにして、孫を
    # 構造として作れなくする。**理由は名指しで書く**——「できません」だけでは
    # どのリンクを外せばよいのか分からない（§4）。
    for link in choice_links(c, include_disabled=True):
        if link['id'] == link_id:
            continue
        if link['child'] == p:
            raise ValueError(f'「{p}」はすでに「{link["parent"]}」の子です。'
                             '親子は1段だけなので、親にはできません'
                             f'（先に「{link["parent"]} → {p}」を外してください）。')
        if link['parent'] == ch:
            raise ValueError(f'「{ch}」はすでに「{link["child"]}」の親です。'
                             '親子は1段だけなので、子にはできません'
                             f'（先に「{ch} → {link["child"]}」を外してください）。')
    cur = c.cursor()
    if link_id:
        cur.execute('SELECT [リンクID] FROM [選択肢リンクマスタ] WHERE [リンクID]=?', [link_id])
    else:
        cur.execute('SELECT [リンクID] FROM [選択肢リンクマスタ] WHERE [子まとまり]=?', [ch])
    hit = cur.fetchone()
    on = -1 if enabled is None else (-1 if enabled else 0)
    if hit:
        sets = ['[親まとまり]=?', '[子まとまり]=?', '[有効]=?', '[更新者ID]=?', '[更新日時]=Now()']
        args = [p, ch, on, uid]
        if note is not None:
            sets.insert(2, '[説明]=?')
            args.insert(2, str(note))
        cur.execute('UPDATE [選択肢リンクマスタ] SET ' + ','.join(sets) + ' WHERE [リンクID]=?',
                    args + [hit[0]])
        c.commit()
        return hit[0]
    cur.execute('INSERT INTO [選択肢リンクマスタ] '
                '([親まとまり],[子まとまり],[説明],[有効],'
                '[登録者ID],[更新者ID],[登録日時],[更新日時]) '
                'VALUES (?,?,?,?,?,?,Now(),Now())',
                [p, ch, str(note or ''), on, uid, uid])
    c.commit()
    cur.execute('SELECT [リンクID] FROM [選択肢リンクマスタ] WHERE [子まとまり]=?', [ch])
    row = cur.fetchone()
    return row[0] if row else None


def choice_link_delete(c, link_id):
    """リンクを外す。**値の`[親の値]`は消さない**——また繋げば続きから使える
    （§9.259の「共通へ戻しても個人の行は消さない」と同じ作法）。"""
    ensure_choice_link_table(c)
    cur = c.cursor()
    cur.execute('DELETE FROM [選択肢リンクマスタ] WHERE [リンクID]=?', [link_id])
    c.commit()


def choice_values(c, name, equipment=None, order=CHOICE_ORDER_DEFAULT,
                  parent_value=None):
    """まとまり名から**選べる値の並び**を返す(§9.221 ③)。有効な行だけを
    表示順で、`[対象設備]`が合うものに絞る。

    **オペレータの「割当が1件も無ければ制限なし」をそのまま引き継ぐ**
    ——空欄＝すべての設備、なので、移行しても現場の見え方は変わらない。

    ここが**唯一の読み口**。オペレータ・機器・スプール・内径・バリ揃え・
    コイル止めの6つは以前それぞれ専用の関数を持っていたが、同じことを
    6箇所に書いていたので、まとまり名が変わるだけの1本にまとめた。"""
    rows = []
    seen = set()
    for r in choice_rows(c):
        if r['name'] != name or not r['value']:
            continue
        if equipment and not choice_matches_equipment(r['equipment'], equipment):
            continue
        # §9.306 親の値で絞る。**親を選んでいないときは絞らない**（利用者の
        # 指示「全部出す（今までどおり）」）——`parent_value`が空／None なら
        # ここは素通りするので、リンクを張っただけでは候補が1つも減らない。
        if parent_value and not choice_matches_parent(r.get('parentValue'), parent_value):
            continue
        key = r['value'].casefold()
        if key in seen:
            continue
        seen.add(key)
        rows.append(r)
    # §9.248 ⑤ **並べ替えは「頼まれたときだけ」**——既定は今までどおり表示順。
    if order == CHOICE_ORDER_USED:
        # **同じ回数のときは表示順のまま**（安定な並び替え）——回数が並ぶ値の
        # 順番が読むたびに変わると、「昨日と場所が違う」になる。
        rows = sorted(rows, key=lambda r: -int(r.get('used') or 0))
    return [r['value'] for r in rows]


# ---------------------------------------------------------------------------
# 6つのマスタの移行(§9.221 ③、利用者の指示)
# ---------------------------------------------------------------------------
# 「オペレータ、機器、スプール種別、内径種別、バリ揃え、コイル止めについても
#  汎用化した操業データ項目マスタに移行させてください」
#
# **1度だけ写す。** 元の表は消さない——現場のデータなので、写しそこねが
# あったときに戻せるようにしておく（§9.180の「共有DBは作り直さない」と
# 同じ考え方）。以後読むのは選択肢マスタだけで、元の表はもう見ない。
#
# (まとまり名, 組み込みキー)。組み込みキーは`BUILTIN_SEEDS`の欄で、
# 移行と同時に`[選択肢名]`を張っておく——張らないと、写した値がどの欄の
# 選択肢なのか誰も知らないまま残る。
LEGACY_CHOICE_GROUPS = (
    ('オペレータ', 'operator'),
    ('板厚測定器', 'thicknessGauge'),
    ('板幅測定器', 'widthGauge'),
    ('内径', 'innerDiameter'),
    ('スプール', 'spool'),
    ('バリ揃え', 'burr'),
    ('コイル止め', 'coilStop'),
)
# 検査員はオペレータと同じ名簿を見る（設備の絞り込みだけしない）。
CHOICE_GROUP_OPERATOR = 'オペレータ'
_LEGACY_MIGRATED_KEY = '__op_choice_legacy_migrated__'


def _legacy_source_rows(c):
    """元の6マスタから (まとまり名, 値, よみ, 対象設備, 表示順) を集める。
    戻りは (行, 読めなかった元表の名前) ——**読めなかった表は飛ばす**が、
    飛ばしたことは呼び出し元へ伝える（1つ無いだけで移行そのものが止まると
    残りの5つが永久に移らない。かといって黙って飛ばすと、その分は
    「移行済み」の目印の裏で永久に取り残される）。"""
    from . import master_repo as mr
    rows = []
    failed = []

    def add(group, values, reading=None, equipment=None):
        for i, v in enumerate(values):
            name = str(v or '').strip()
            if name:
                rows.append((group, name, (reading or {}).get(name, ''),
                             (equipment or {}).get(name, ''), (i + 1) * 10))

    # **移行元の表が無いのは「失敗」ではない**（§9.255 ①）。移行済みの表を
    # 消した端末・新規導入の端末では最初から無いので、無いことを`failed`へ
    # 数えると**目印が永久に立たず、開くたびに写しを試し続ける**（しかも
    # `ensure_*`が作り直していたので、消した表が毎回復活していた）。
    from ..db_access import tables as _tables
    have = set(_tables(c))
    try:
        if mr.OPERATOR_MASTER_TABLE in have:
            cur = c.cursor()
            cur.execute('SELECT [オペレータID],[氏名],[ﾖﾐｶﾞﾅ],[表示順],[有効] '
                        'FROM [オペレータマスタ] ORDER BY [表示順],[氏名]')
            eqmap = mr.operator_equipment_map(c)
            names, reading, equip = [], {}, {}
            for r in cur.fetchall():
                if r[4] is not None and not bool(r[4]):
                    continue
                nm = str(r[1] or '').strip()
                if not nm:
                    continue
                names.append(nm)
                reading[nm] = str(r[2] or '')
                equip[nm] = _norm_equipment(eqmap.get(r[0]) or [])
            add(CHOICE_GROUP_OPERATOR, names, reading, equip)
    except Exception:
        failed.append(CHOICE_GROUP_OPERATOR)
    for group, kind in (('板厚測定器', '板厚'), ('板幅測定器', '板幅')):
        try:
            add(group, mr.read_device_names(c, kind))
        except Exception:
            failed.append(group)
    for group, fn in (('内径', 'read_inner_names'), ('スプール', 'read_spool_names'),
                      ('バリ揃え', 'read_burr_names'), ('コイル止め', 'read_coil_stop_names')):
        try:
            add(group, getattr(mr, fn)(c))
        except Exception:
            failed.append(group)
    return rows, failed


def migrate_legacy_choice_masters(c):
    """1度だけ、6つのマスタを選択肢マスタへ写す。**目印はパス設定マスタ**
    （データソースの種まきと同じ作法）——「行が無ければ写す」にすると、
    利用者が全部消した瞬間に復活する消せないマスタになる。"""
    from ..db_access import path_config_rows, set_path_config
    ensure_choice_table(c)
    if path_config_rows(c).get(_LEGACY_MIGRATED_KEY):
        return False
    rows, failed = _legacy_source_rows(c)
    for group, value, reading, equipment, order in rows:
        try:
            choice_upsert(c, group, value, 'migrate:legacy', order=order,
                          reading=reading, equipment=equipment)
        except ValueError:
            continue
    # 組み込みの欄へ**まとまり名を張る**。触っていない欄だけ（既に選ばれて
    # いれば現場の設定が勝つ）。
    ensure_item_table(c)
    cur = c.cursor()
    for group, key in LEGACY_CHOICE_GROUPS:
        cur.execute(f"UPDATE [{ITEM_TABLE}] SET [選択肢名]=? "
                    "WHERE [組み込みキー]=? AND ([選択肢名] IS NULL OR [選択肢名]='')",
                    [group, key])
    c.commit()
    # **1つでも読めなかったら目印を立てない。** 立ててしまうと、読めなかった
    # まとまり（列名のゆれ・古い版に無い列・共有越しの一時的な失敗——まさに
    # 上の except が吸収している事象）が0件のまま「移行済み」になり、次に
    # 開いたときには二度と写されない。写せたぶんは既に入っているので、
    # 次回はそこから続き（choice_upsert は同じ値を二重に作らない）。
    if failed:
        return False
    set_path_config(c, _LEGACY_MIGRATED_KEY, 'done', 'migrate:legacy')
    return True


def choice_upsert(c, name, value, uid, order=None, choice_id=None, enabled=None, note=None,
                  reading=None, equipment=None, parent_value=None):
    """選択肢を1件書く。**`enabled=None`は「送っていない」で、今の値を残す**
       （§9.212 ②）——`True`を既定にすると、説明だけを直す呼び出しが
       「出さない」にしてあった行を毎回「出す」へ戻す。新規のときだけ`True`。"""
    ensure_choice_table(c)
    name = str(name or '').strip()
    value = str(value if value is not None else '').strip()
    if not name:
        raise ValueError('選択肢名を入力してください。')
    if not value:
        raise ValueError('値を入力してください。')
    cur = c.cursor()
    if choice_id is not None:
        # **並び順を渡していないときは今の値を残す**——空欄で保存したつもりが
        # NULLになると、その行だけ先頭へ飛ぶ（送っていない設定を消さない・§9.212 ②）。
        if order is None:
            cur.execute('SELECT [表示順] FROM [操業データ選択肢マスタ] WHERE [選択肢ID]=?',
                        [int(choice_id)])
            hit = cur.fetchone()
            order = hit[0] if hit else None
        # **送っていない項目は今の値を残す**（§9.212 ②）。1つ書き漏らすと
        # その設定だけが保存のたびに消える。
        cur.execute('SELECT [説明],[よみ],[対象設備],[有効],[親の値] FROM [操業データ選択肢マスタ] '
                    'WHERE [選択肢ID]=?', [int(choice_id)])
        hit = cur.fetchone() or ['', '', '', -1, '']
        if note is None:
            note = hit[0] or ''
        if reading is None:
            reading = hit[1] or ''
        if equipment is None:
            equipment = hit[2] or ''
        if enabled is None:
            enabled = bool(hit[3])
        # §9.306 **送っていない親の値は今の値を残す**（§9.212 ②）——1つ
        # 書き漏らすと、他の欄を直しただけで親子の割り当てが消える。
        if parent_value is None:
            parent_value = (hit[4] if len(hit) > 4 else '') or ''
        cur.execute('UPDATE [操業データ選択肢マスタ] SET [選択肢名]=?,[値]=?,[説明]=?,[表示順]=?,'
                    '[有効]=?,[よみ]=?,[対象設備]=?,[親の値]=?,[更新者ID]=?,[更新日時]=Now() '
                    'WHERE [選択肢ID]=?',
                    [name, value, str(note or ''), order, -1 if enabled else 0,
                     str(reading or ''), _norm_equipment(equipment),
                     _norm_equipment(parent_value), uid, int(choice_id)])
        c.commit()
        return int(choice_id)
    # 自然キーは(選択肢名,値)。同じ値を2つ並べない——どちらを選んでも同じ。
    cur.execute('SELECT [選択肢ID],[表示順],[説明],[よみ],[対象設備],[有効],[親の値] '
                'FROM [操業データ選択肢マスタ] '
                'WHERE [選択肢名]=? AND [値]=?', [name, value])
    hit = cur.fetchone()
    if hit:
        cur.execute('UPDATE [操業データ選択肢マスタ] SET [表示順]=?,[説明]=?,[有効]=?,'
                    '[よみ]=?,[対象設備]=?,[親の値]=?,[更新者ID]=?,[更新日時]=Now() '
                    'WHERE [選択肢ID]=?',
                    [hit[1] if order is None else order,
                     str((hit[2] if note is None else note) or ''),
                     -1 if (bool(hit[5]) if enabled is None else enabled) else 0,
                     str((hit[3] if reading is None else reading) or ''),
                     _norm_equipment(hit[4] if equipment is None else equipment),
                     _norm_equipment((hit[6] if len(hit) > 6 else '')
                                     if parent_value is None else parent_value),
                     uid, hit[0]])
        c.commit()
        return int(hit[0])
    if order is None:
        cur.execute('SELECT MAX([表示順]) FROM [操業データ選択肢マスタ] WHERE [選択肢名]=?', [name])
        top = cur.fetchone()[0] or 0
        order = int(top) + 10
    cur.execute('INSERT INTO [操業データ選択肢マスタ] '
                '([選択肢名],[値],[説明],[表示順],[有効],[よみ],[対象設備],[親の値],'
                '[登録者ID],[更新者ID],[登録日時],[更新日時]) '
                'VALUES (?,?,?,?,?,?,?,?,?,?,Now(),Now())',
                [name, value, str(note or ''), order,
                 -1 if (True if enabled is None else enabled) else 0,
                 str(reading or ''), _norm_equipment(equipment),
                 _norm_equipment(parent_value), uid, uid])
    c.commit()
    return int(cur.lastrowid)


def choice_rename_group(c, src, dst, uid):
    """まとまりの名前を変える(§9.221 ②)。**参照している項目の`[選択肢名]`も
    一緒に書き換える**——結び付けは名前なので(§9.215)、片方だけ変えると
    その項目の選択肢が黙って消える。

    移動先に同じ値が既にあるときは**その行を残して古いほうを消す**
    （同じ値が2つ並ぶと、どちらを選んでも同じで選ぶ意味が無い）。"""
    ensure_choice_table(c)
    src = str(src or '').strip()
    dst = str(dst or '').strip()
    if not src or not dst:
        raise ValueError('まとまり名を入力してください。')
    cur = c.cursor()
    cur.execute(f'SELECT [値] FROM [{CHOICE_TABLE}] WHERE [選択肢名]=?', [dst])
    taken = {str(r[0] or '').strip().casefold() for r in cur.fetchall()}
    cur.execute(f'SELECT [選択肢ID],[値] FROM [{CHOICE_TABLE}] WHERE [選択肢名]=?', [src])
    moved = 0
    for cid, val in cur.fetchall():
        if str(val or '').strip().casefold() in taken:
            cur.execute(f'DELETE FROM [{CHOICE_TABLE}] WHERE [選択肢ID]=?', [cid])
            continue
        cur.execute(f'UPDATE [{CHOICE_TABLE}] SET [選択肢名]=?,[更新者ID]=?,[更新日時]=Now() '
                    'WHERE [選択肢ID]=?', [dst, uid, cid])
        moved += 1
    ensure_item_table(c)
    cur.execute(f'UPDATE [{ITEM_TABLE}] SET [選択肢名]=?,[更新者ID]=?,[更新日時]=Now() '
                'WHERE [選択肢名]=?', [dst, uid, src])
    c.commit()
    return moved


def choice_delete_group(c, name, uid):
    """まとまりごと消す。**使っている項目があれば断る**（§9.216 ④の裏返し
    ——消すとその項目は黙って空の欄になる）。"""
    ensure_choice_table(c)
    name = str(name or '').strip()
    if not name:
        raise ValueError('まとまり名がありません。')
    # **読めなかったら消さない**（§9.117）。`choice_usage`が None を返すのは
    # 「使っている項目を数えられなかった」であって「誰も使っていない」では
    # ない。取り違えると、使用中のまとまりを丸ごと物理削除して、参照して
    # いた項目が黙って空の欄になる。
    usage = choice_usage(c)
    if usage is None:
        raise ValueError('「%s」を使っている項目を確かめられませんでした。'
                         '消すと使っている項目の選択肢が黙って空になるため、'
                         '中止します。マスタ管理を開き直してからもう一度お試し'
                         'ください。' % name)
    used = usage.get(name) or []
    if used:
        raise ValueError('「%s」は %d 件の項目が使っています（%s）。先に項目側の'
                         '選択肢を差し替えてください。' % (name, len(used), '、'.join(used[:4])))
    cur = c.cursor()
    cur.execute(f'DELETE FROM [{CHOICE_TABLE}] WHERE [選択肢名]=?', [name])
    c.commit()
    return cur.rowcount


def choice_reorder(c, ids, uid):
    """1つのまとまりの中の並びをまとめて書く。**渡された行だけ**を触る
    （§9.212 ②と同じ約束）。"""
    ensure_choice_table(c)
    cur = c.cursor()
    n = 0
    for i, cid in enumerate(ids):
        try:
            key = int(cid)
        except (TypeError, ValueError):
            continue
        cur.execute(f'UPDATE [{CHOICE_TABLE}] SET [表示順]=?,[更新者ID]=?,[更新日時]=Now() '
                    'WHERE [選択肢ID]=?', [(i + 1) * 10, uid, key])
        n += cur.rowcount
    c.commit()
    return n


