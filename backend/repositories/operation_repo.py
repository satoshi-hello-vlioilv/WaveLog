def form_for_equipment(c, equipment):
    """その設備の入力欄の定義一式。**選択肢は名前で解決してから渡す**
    ——画面が2度目の問い合わせをしなくて済む（測定画面は開いた瞬間に要る）。
    **名前が見つからない選択肢は空のまま返し、項目は残す**（設定の途中でも
    入力欄が丸ごと消えないように）。"""
    items = items_for_equipment(c, equipment)
    # **選択肢もこの設備のものだけ**（§9.221 ③の追補）。組み込みの欄は
    # `choice_values(c,name,equipment)`で絞られているので、ここで絞らないと
    # 同じまとまりが欄によって違う中身になる。
    cmap = choice_map(c, equipment)
    notes = choice_notes(c, equipment)
    # ---------- 親子（§9.306、利用者の指示） ----------
    # **「この親の値のときに出る値」はサーバーが先に解いて渡す**（§9.163）。
    # 親の欄は打つたびに変わるので画面が絞ることになるが、カンマ区切り・
    # `'*'`・空欄の読み方まで画面へ写すと、**同じ書式の読み方が2通りになる**
    # （`[対象設備]`で一度そうしかけた形）。親の値ごとの答えを先に配れば、
    # 画面は引くだけで済む。親の値は数個なので、配る量も知れている。
    links = {x['child']: x['parent'] for x in choice_links(c)}
    # どの欄が親の値を持つか。**同じまとまりを使う欄が複数あれば表示順で先の
    # ものが親**——決めないと「どの欄で絞るのか」が端末ごとに変わる。
    holder = {}
    for it in items:
        g = it.get('choice') or ''
        if g and g not in holder:
            holder[g] = {'name': it['name'], 'builtin': it.get('builtin') or ''}
    # §9.288 ③ `索引`が頭文字で束ねるのに使う。**説明と同じ作法**——
    # 有るものだけ渡す（無いのか読めていないのかを画面が区別できるように）。
    readings = choice_readings(c, equipment)
    out = []
    for it in items:
        row = dict(it)
        # §9.248 ⑤ 並びは**項目の設定**で決まる（既定は表示順＝今までどおり）。
        # **効かない入力方法では並べ替えない**（§4）——札を並べる形で順番が
        # 変わると、同じ欄なのに押す場所が毎回動く。
        row['choices'] = (choice_list(cmap, it['choice'],
                                      it['choiceOrder'] if choice_order_usable(it['widgetLive'])
                                      else CHOICE_ORDER_DEFAULT)
                          if it['choice'] else [])
        # 説明つきで選ばせるのに要る（§9.218 ②）。**説明のある値だけ**入れる。
        row['choiceNotes'] = dict(notes.get(it['choice'], {})) if it['choice'] else {}
        row['choiceReadings'] = dict(readings.get(it['choice'], {})) if it['choice'] else {}
        row['choiceMissing'] = bool(it['choice']) and it['choice'] not in cmap
        # --- §9.306 親子 ---
        # `choiceParent`＝親のまとまり名／`parentField`＝その値を持つ欄／
        # `choicesByParent`＝親の値ごとに出る値の並び。
        # **親を選んでいないときは絞らない**（利用者の指示）ので、画面は
        # 親が空なら`choices`をそのまま使う——ここには`''`の鍵を入れない。
        pg = links.get(it['choice']) if it['choice'] else ''
        row['choiceParent'] = pg or ''
        row['parentField'] = holder.get(pg) if pg else None
        row['choicesByParent'] = {}
        if pg and it['choice']:
            for pv in choice_list(cmap, pg, CHOICE_ORDER_DEFAULT):
                row['choicesByParent'][pv] = choice_values(
                    c, it['choice'], equipment,
                    it['choiceOrder'] if choice_order_usable(it['widgetLive'])
                    else CHOICE_ORDER_DEFAULT,
                    parent_value=pv)
        # --- §9.231 ② 上下限をマスタから引き直す ---
        # **解決するのはここ1箇所**——測定画面は`min`/`max`をそのまま使うので、
        # 画面側に「出どころを引く」処理を書かない（§9.163）。
        # **引けなかったら上限を掛けない**（`None`のまま）。0にすると
        # 「何を打っても弾かれる欄」になる。どこから来た値かは`*FromLabel`で
        # 画面に出す（§6「出どころ・単位・根拠を画面に出す」）。
        for side, col in (('min', 'minFrom'), ('max', 'maxFrom')):
            key = row.get(col) or ''
            if not key:
                continue
            v = resolve_limit(c, key, equipment)
            row[side] = v
            row[col + 'Label'] = limit_source_label(key)
            row[col + 'Missing'] = v is None
        out.append(row)
    # **出さない組み込みの欄は名指しで返す**(§9.216 ②)。画面はマスタに載って
    # いる欄しか差配しないので、「無効にした」「この設備では使わない」を
    # 伝えないと**入力欄だけが今までどおり出たまま**になる（マスタで外した
    # つもりの欄が消えない、という分かりにくい壊れ方）。
    known = {x['builtin'] for x in item_rows(c, True) if x['builtin']}
    live = {x['builtin'] for x in items if x['builtin']}
    # **役割を譲った組み込みの欄も下ろす**（§9.223 ①）。設定画面には
    # 「役割を別の項目へ移すと、この欄は自動で下がります」と書いてあるので、
    # 下ろさないと**同じ役割の欄が2つ並ぶ**（どちらの値が使われるのか
    # 決められない＝§4の「書いたのに起きない」）。
    down = set(stepped_down_builtins(items))
    if down:
        out = [r for r in out if r.get('builtin') not in down]
    return {'items': out, 'builtinOff': sorted((known - live) | down),
            # §9.256。式が参照できる**取得データの呼び名**。**鍵ではなく
            # 呼び名で書かせる**ので（§CLAUDE 2「思い出させない」）、
            # 画面は`[ロット番号]`と`lot.lotNo`を結ぶこの表を要る。
            # **語彙はサーバーが持つ**（§9.163）——画面へ写すと、値を1つ
            # 足したときに2箇所直すことになる。
            'autoValues': [{'key': k, 'label': lb, 'group': g, 'unit': u, 'note': n}
                           for k, lb, g, u, n in AUTO_VALUES],
            # **式で作る自動値の鍵も答える**——画面へ綴りを書き写さない
            # （`tests/test_opauto.js`が機械で見張っている）。
            'autoFormulaKey': AUTO_FORMULA_KEY,
            'limitSources': [{'key': k, 'label': l, 'unit': u} for k, l, u in LIMIT_SOURCES],
            'gridCols': GRID_COLS, 'spanUnit': SPAN_UNIT,
            'widgets': list(WIDGETS),
            'widgetFamilies': {k: list(v) for k, v in WIDGET_FAMILIES.items()},
            'places': list(PLACES)}
