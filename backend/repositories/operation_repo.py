def resolve_limit(c, key, equipment):
    """出どころの鍵から**いまの値**を引く。引けなければ`None`。

    **引けなかったことを0にしないこと**——0にすると「上限0」という、
    何を打っても弾かれる欄になる（§9.114「空欄は未設定であって0ではない」）。
    読むだけなので、失敗しても例外は投げない（§9.163）。
    """
    key = normalize_limit_source(key)
    if not key:
        return None
    try:
        from . import master_repo as mr
        if key == 'equipment.maxLineSpeed':
            return mr.read_equipment_max_line_speed(c, equipment)
        if key == 'equipment.maxStrips':
            n = mr.read_equipment_max_strips(c, equipment)
            return float(n) if n else None
    except Exception:
        return None
    return None


def _ensure_item_columns(c):
    cur = c.cursor()
    have = {r[1] for r in cur.execute(f'PRAGMA table_info([{ITEM_TABLE}])')}
    # **マスの数え方が変わったことの目印は「列そのもの」**（§9.218 ②）。
    # 6マス→12マスにしたので、保存済みの`[列幅]`は倍にしないと**全部が
    # 半分の幅になる**。専用の目印を別に持つと、それを消したときに二重に
    # 掛かる——`[入力方法]`が無い＝12マスへ移る前の行、という1つの事実で
    # 判断する（列を足す作業そのものが1度きりなので、目印として確実）。
    grow = '入力方法' not in have and '列幅' in have
    # **足すのは`add_missing_columns()`の1箇所**（§9.315）。ここが
    # 「読んでから足すまでに別のリクエストが足す」で落ちていた
    # （利用者の報告『duplicate column name: 丸め方』。その版へ上げた
    # 最初の1回だけ起き、リロードすると直る）。
    added = add_missing_columns(c, ITEM_TABLE, _ITEM_ADDED_COLUMNS)
    if grow:
        cur.execute(f'UPDATE [{ITEM_TABLE}] SET [列幅]=[列幅]*{SPAN_UNIT} '
                    'WHERE [列幅] IS NOT NULL AND [列幅]>0')
        c.commit()
    return bool(added)


def _seed_builtins(c):
    """準備の入力欄をマスタの行として置く。**1度だけ**（組み込みの行が
    1つも無いときだけ）——利用者が消した行を毎回作り直すと、消せない設定に
    なってしまう。"""
    cur = c.cursor()
    cur.execute(f"SELECT COUNT(*) FROM [{ITEM_TABLE}] "
                "WHERE [組み込みキー] IS NOT NULL AND [組み込みキー]<>''")
    if (cur.fetchone() or [0])[0]:
        return False
