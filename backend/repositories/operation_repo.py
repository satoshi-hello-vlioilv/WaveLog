def _same_as_common(key, value, common):
    """その鍵の値が共通の行と同じか（§9.239 ②）。

    **形をそろえてから比べる**——`showWhen`は共通側がリスト・上書き側が
    カンマ区切りの文字列、`fold`/`dummy`はAccess由来の`-1`と`True`という形で
    同じことを言う。素で比べると「同じなのに違う」と判定され、落とすはずの
    鍵が全部残る（＝この関数を足した意味が無くなる）。"""
    cur = common.get(key)
    if key == 'showWhen':
        norm = lambda v: ','.join(
            x.strip() for x in (v if isinstance(v, (list, tuple)) else str(v or '').split(','))
            if str(x).strip())
        return norm(value) == norm(cur)
    if key in ('fold', 'dummy'):
        return bool(value) == bool(cur)
    if key in ('order', 'span', 'groupSpan'):
        try:
            return int(value) == int(cur if cur is not None else 0)
        except (TypeError, ValueError):
            return False
    return str(value or '').strip() == str(cur or '').strip()


def _override_write(cur, uid, item_id, equipment, patch, common=None):
    """1行の「設備ごとの上書き」を書く（§9.239 ②）。

    **触った項目だけを重ねる**——`patch`に無い鍵はそのまま残す（§9.212 ②）。

    **共通と同じ値になった鍵は落とす**（`common`を渡したときだけ）。
    落とさないと、盤で1回並べ替えただけで**その設備の全部の欄が共通から
    切り離される**——以降どれだけ共通を直しても、その設備には1つも届かない
    （§9.198「既定へ戻す＝行を消す」と同じ理由。設定が黙って効かなくなる形は
    §CLAUDE 4）。判定に使う`common`は**上書きを重ねる前の行**であること。"""
    cur.execute(f'SELECT [設備別レイアウト] FROM [{ITEM_TABLE}] WHERE [項目ID]=?', [item_id])
    hit = cur.fetchone()
    m = _override_map(hit[0] if hit else None)
    eq = str(equipment or '').strip()
    if not eq:
        return 0
    one = dict(m.get(eq) or {})
    for k, v in (patch or {}).items():
        if k not in LAYOUT_OVERRIDE_KEYS:
            continue
        if v is None or (common is not None and _same_as_common(k, v, common)):
            one.pop(k, None)
        else:
            one[k] = v
    if one:
        m[eq] = one
    else:
        m.pop(eq, None)
    cur.execute(f'UPDATE [{ITEM_TABLE}] SET [設備別レイアウト]=?,'
                '[更新者ID]=?,[更新日時]=Now() WHERE [項目ID]=?',
                [_override_json(m), uid, item_id])
    return cur.rowcount


def item_layout_save(c, uid, rows, equipment=''):
    """並び・群・列幅・置き場・必須・出す/出さないを**まとめて1回で**書く
    (§9.216 ②)。D&Dで並べ替える画面なので1行ずつのPOSTでは往復が増え、
    途中で切れると**並びが半分だけ変わった状態**が残る。

    **渡された行だけを書く**——一覧に出していない設備の行を巻き添えに
    しない（§9.212 ②と同じ約束）。

    **順番は「席の入れ替え」で書く**（§9.219 ③）。以前は渡された順に
    `(i+1)*10`を振っていたため、**一部の行だけを渡すと、その行が先頭へ
    集まって他の群のあいだへ割り込んだ**——同じ群が3つの帯に割れ、
    「その群へ項目を移動できない」という形で実機に出た。いま在る席
    （表示順）を集めて昇順に均し、**新しい並びでその席へ座らせる**ので、
    渡していない行との前後関係は1つも動かない。"""
    ensure_item_table(c)
    cur = c.cursor()
    todo = []
    for r in (rows or []):
        try:
            todo.append((int(r.get('id')), r))
        except (TypeError, ValueError):
            continue
    if not todo:
        return 0
    slots = []
    for item_id, _r in todo:
        cur.execute(f'SELECT [表示順] FROM [{ITEM_TABLE}] WHERE [項目ID]=?', [item_id])
        hit = cur.fetchone()
        slots.append(int(hit[0]) if hit and hit[0] is not None else 0)
    slots.sort()
    # 同じ席が2つあると順番が決まらないので、**厳密に増える形へ均す**。
    for i in range(1, len(slots)):
        if slots[i] <= slots[i - 1]:
            slots[i] = slots[i - 1] + 1
    n = 0
    eq = str(equipment or '').strip()
    if eq:
        # **設備を選んで並べているときは共通の行を書き換えない**（§9.239 ②）。
        # 書き換えると、その設備で並べ替えただけで**他の設備の並びも動く**
        # ——「設備ごと」にした意味が消える。
        # **共通と同じ値は上書きに残さない**（§9.239 ②）。盤は画面に出ている
        # 全部のカードを送ってくるので、比べずに書くと**1回並べ替えただけで
        # その設備の全部の欄が共通から切り離される**。材料は`item_rows()`＝
        # **上書きを重ねる前の行**（`items_for_equipment()`は重ねたあとなので
        # 使えない——自分の上書きと比べることになり、1つも落ちない）。
        base = {x['id']: x for x in item_rows(c, True)}
        for i, (item_id, r) in enumerate(todo):
            when = r.get('showWhen')
            if isinstance(when, (list, tuple)):
                when = ','.join(str(x).strip() for x in when if str(x).strip())
            n += _override_write(cur, uid, item_id, eq, {
                'group': str(r.get('group') or '').strip(),
                'order': slots[i],
                'span': normalize_span(r.get('span')),
                'place': normalize_place(r.get('place')),
                'fold': bool(r.get('fold')),
                'showWhen': str(when or ''),
            }, common=base.get(item_id))
        c.commit()
        return n
    for i, (item_id, r) in enumerate(todo):
        when = r.get('showWhen')
        if isinstance(when, (list, tuple)):
            when = ','.join(str(x).strip() for x in when if str(x).strip())
        cur.execute('UPDATE [操業データ項目マスタ] SET [群]=?,[表示順]=?,[列幅]=?,[置き場]=?,'
                    '[必須]=?,[有効]=?,[群折りたたみ]=?,[表示条件]=?,'
                    '[更新者ID]=?,[更新日時]=Now() WHERE [項目ID]=?',
                    [str(r.get('group') or '').strip(), slots[i],
                     normalize_span(r.get('span')), normalize_place(r.get('place')),
                     -1 if r.get('required') else 0,
                     0 if r.get('enabled') is False else -1,
                     -1 if r.get('fold') else 0,
                     str(when or ''), uid, item_id])
        n += cur.rowcount
    c.commit()
    return n


def record_layout_save(c, uid, rows):
    """③「記録した値」のカードの配置を**まとめて1回で**書く（§9.243）。

    利用者の指示:
      「現在操業データ項目マスタで設定している内容を候補に出して視覚的に
       配置して設定できるようなマスタを別で追加立ち上げして簡単にD&Dで
       配置修正再設定、編集できるようにしてほしいです」

    D&Dで組み替える盤なので、1行ずつのPOSTでは往復が増え、途中で切れると
    **並びが半分だけ変わった状態**が残る（`item_layout_save`と同じ理由）。

    書くのは3つだけ——`[記録表示]`（カードへ出すか）・`[記録群]`（カードの中の
    見出し）・`[記録順]`（カードの中の並び）。**型・選択肢・役割・意匠には
    触らない**（あちらは「何を記録するか」で、ここは「どう並べるか」）。

    **渡された行だけを書く**（§9.212 ②）——盤に出していない設備の行を
    巻き添えにしない。

    **群が空なら`[記録群]`も空へ戻す**——空＝この項目の`[群]`に従う、という
    既定へ帰れること（戻せない設定を作らない）。

    **順番も同じように戻せること**（`follow=True`で`[記録順]`をNULLへ）。
    ここを「必ず`(i+1)*10`で振り直す」にすると、盤の「既定へ戻す」を押しても
    **今日の`[表示順]`と同じ数を焼き付けるだけ**になり、あとで
    操業データ項目マスタの`[表示順]`を変えてもカードが追随しない
    （**押しても戻らない設定**になる。§9.169で「押しても保存されない設定」を
    作った罠と同じ形）。触っていない項目は`follow`のまま送られてくるので、
    **盤で掴んだ項目だけ**が並びから切り離される。

    順番は渡された順に`(i+1)*10`：ここは**カードの中だけの並び**で、他の画面と
    席を分け合っていないので、`item_layout_save`のような席の入れ替えは要らない。
    """
    ensure_item_table(c)
    cur = c.cursor()
    n = 0
    for i, r in enumerate(rows or []):
        try:
            item_id = int(r.get('id'))
        except (TypeError, ValueError):
            continue
        show = r.get('show')
        group = str(r.get('group') or '').strip()
        order = None if r.get('follow') else (i + 1) * 10
        cur.execute(f'UPDATE [{ITEM_TABLE}] SET [記録表示]=?,[記録群]=?,[記録順]=?,'
                    '[更新者ID]=?,[更新日時]=Now() WHERE [項目ID]=?',
                    [0 if show is False else -1, group, order, uid, item_id])
        n += cur.rowcount if cur.rowcount and cur.rowcount > 0 else 1
    c.commit()
    return n


def group_flags_save(c, uid, place, group, fold, show_when, group_span=None,
                     dummy=None, equipment=''):
    """群のふるまい（畳む・開く条件・幅）だけを、その群の全部の行へ書く
    (§9.216 ④／§9.226 ③)。

    **`item_layout_save`で代用しないこと。** あちらは行の中身をまるごと
    書くので、直前に1件だけ更新した内容（列幅など）を**古い写しで
    上書きしてしまう**（実際にそれで「列幅を変えても戻る」が起きた）。
    ここで触るのは3列だけ。

    **群幅は渡されたときだけ書く**（§9.212 ②の「送った項目だけ書く」）。
    畳むボタンを押しただけで幅まで既定へ戻るのでは、設定が黙って消える。"""
    ensure_item_table(c)
    if isinstance(show_when, (list, tuple)):
        show_when = ','.join(str(x).strip() for x in show_when if str(x).strip())
    cur = c.cursor()
    eq = str(equipment or '').strip()
    if eq:
        # **設備を選んでいるときは上書き側へ**（§9.239 ②）。以前はWHEREに
        # `[設備名]`が無く、設備Aで群を畳んだだけで**全設備の行**が畳まれた
        # ——「半分だけ設備ごと」という一番分かりにくい状態になる。
        # **効いている群で引く**——上書きで別の群へ移した項目は、共通の
        # `[群]`列とは食い違う。共通の列で引くと「盤で同じ帯に並んでいる
        # のに畳めない項目」が出る（設備ごとにした意味が半分消える）。
        want_g, want_p = str(group or ''), normalize_place(place)
        ids = [x['id'] for x in items_for_equipment(c, eq, True)
               if str(x.get('group') or '') == want_g
               and normalize_place(x.get('place')) == want_p]
        patch = {'fold': bool(fold), 'showWhen': str(show_when or '')}
        if group_span is not None:
            patch['groupSpan'] = normalize_group_span(group_span)
        if dummy is not None:
            patch['dummy'] = bool(dummy)
        n = 0
        # ここも**共通と同じ値なら上書きに残さない**（§9.239 ②）。畳んで
        # 開き直しただけで、その群が共通から切り離されてしまう。
        base = {x['id']: x for x in item_rows(c, True)}
        for i in ids:
            n += _override_write(cur, uid, i, eq, patch, common=base.get(i))
        c.commit()
        return n
    sets = '[群折りたたみ]=?,[表示条件]=?'
    args = [-1 if fold else 0, str(show_when or '')]
    if group_span is not None:
        sets += ',[群幅]=?'
        args.append(normalize_group_span(group_span))
    # ダミーも**渡されたときだけ**（§9.212 ②）。
    if dummy is not None:
        sets += ',[ダミー]=?'
        args.append(-1 if dummy else 0)
    cur.execute(f'UPDATE [{ITEM_TABLE}] SET {sets},'
                '[更新者ID]=?,[更新日時]=Now() '
                'WHERE COALESCE([群],\'\')=? AND COALESCE(NULLIF([置き場],\'\'),?)=?',
                args + [uid, str(group or ''), PLACE_PREP, normalize_place(place)])
    c.commit()
    return cur.rowcount


def item_delete(c, item_id, uid):
    ensure_item_table(c)
    cur = c.cursor()
    cur.execute('DELETE FROM [操業データ項目マスタ] WHERE [項目ID]=?', [int(item_id)])
    c.commit()
    return cur.rowcount


