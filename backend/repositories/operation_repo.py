# 組み込みの欄の初期値（§9.286 ⑤、利用者の指示）
# ---------------------------------------------------------------------------
# 「操業データのカスタム機能ができる前から入力値としてあった項目で、途中から
#  汎用仕様に落とし込んだものの中に、初期値を『-』でハードコーディングして
#  いるものが残っており、『オペレータ』や『検査員』や『板厚測定器』など他にも
#  同様に存在しています。初期値も含めて汎用化対応しているので、
#  ハードコーディング部分を除去してきれいに汎用部品のみで対応できるように
#  してください。」
#
# **直したのはサーバーではなく画面のほう**（`base.js`の`optionFill()`と
# `measurement-view.js`の`blankMeasure()`）。`-`は「選ばない」の**札の字**で
# あって値ではないのに、画面が値として`operator:'-'`を書き込んでいたため、
# `applyInitials()`が見る「まだ何も選ばれていない」の判定を画面の側が先に
# 埋めてしまい、**マスタの`[初期値]`が一度も効かなかった**。
#
# **`上出し`・`指定なし`のような「値として意味のある既定」は触っていない**
# ——あれは「選んでいない」ではなく1つの選択肢なので、空にすると
# 設定を触っていない現場の見え方が黙って変わる（§9.132）。


def ensure_item_table(c):
    names = tables(c)
    if ITEM_TABLE not in names:
        cur = c.cursor()
        cur.execute('CREATE TABLE [操業データ項目マスタ] ('
                    '[項目ID] INTEGER PRIMARY KEY AUTOINCREMENT, [設備名] TEXT, [群] TEXT, '
                    '[項目名] TEXT, [表示順] INTEGER, [型] TEXT, [小数桁] INTEGER, '
                    '[最小値] REAL, [最大値] REAL, [選択肢名] TEXT, [単位] TEXT, '
                    '[必須] INTEGER, [備考] TEXT, [有効] INTEGER, '
                    '[組み込みキー] TEXT, [置き場] TEXT, [列幅] INTEGER, '
                    '[群折りたたみ] INTEGER, [表示条件] TEXT, [入力方法] TEXT, '
                    '[初期値] TEXT, [手打ち可] INTEGER, [ステップ量] REAL, '
                    '[単位位置] TEXT, [文字寄せ] TEXT, [表示書式] TEXT, [表示桁数] INTEGER, '
                    '[登録者ID] TEXT, [更新者ID] TEXT, [登録日時] DATETIME, [更新日時] DATETIME)')
        c.commit()
        _seed_items(c)
        _seed_builtins(c)
        return True
    _ensure_item_columns(c)
    _seed_builtins(c)
    # **後から足した組み込みの欄も入れる**（§9.232）。1度だけ・まだ無い鍵だけ。
    try:
        seed_mother_builtins(c)
    except Exception:
        pass
    return False


