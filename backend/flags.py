"""flags.py: 画面から来る「入/切」を真偽へ直す。**答えるのはここ1箇所**（§9.324 R4）。

マスタ管理の汎用フォームは選択欄しか持たないので、真偽は**呼び名**で届く
（`有効`/`無効`・`出す`/`出さない`・`登録しない`）。文字列をそのまま`bool()`へ
渡すと`bool('無効')`は真で、**外したつもりが一度も保存できない**——この罠を
帳票ブロック(`_on`)・選択肢(`_choice_on`)・ロール(`_on`)・手打ちの登録
(`_inline_add_on`)の4箇所が**それぞれ別の語彙で**書いていた（§9.222 ⑥／
§9.320-E／§9.323 ①で「3度目」と数えたもの）。語彙が4通りに散ると、
5つ目を足すときに必ずどれかを見落とす。

約束は2つ:
  ・**`None`は「送っていない」**（§9.212 ②）——Falseへ倒さない。repo側が
    「今の値のまま」と読む。
  ・**切の語彙は`OFF_WORDS`の1つ**——画面が出しうる呼び名は全部ここに並べる。
    ふつうの呼び出しは既定のまま使う。Excel取り込みのように**空欄を「触らない」
    ではなく「入」と読む**場面だけ、`off=`で空文字を外して呼ぶ。
"""

# 「できない」は刃組基準値の`中抜き可`（§9.377）、「載せない」は`一体型潤滑`（§9.532）。**画面が出しうる呼び名は
# 全部ここに並べる**——並べ忘れると`bool('できない')`が真になり、
# 「できない」を選んでも一度も保存できない欄になる（この罠の5度目）。
OFF_WORDS = ('無効', '出さない', '登録しない', 'しない', 'できない', '載せない', 'false', '0', '')


def flag_of(v, off=OFF_WORDS):
    """呼び名／真偽値／数を真偽へ。`None`は`None`のまま（「送っていない」）。"""
    if v is None:
        return None
    if isinstance(v, str):
        return v.strip() not in off
    return bool(v)


def text_or(x, key):
    """`<key>Text`（呼び名）が来ていればそれ、無ければ`<key>`（§9.320-E）。

    汎用フォームは`enabledText`のように呼び名で送り、APIを直に叩く側は
    `enabled`で送る。どちらも受け、**呼び名を優先する**（同じ要求に両方あるなら
    画面が出したほうが正）。"""
    t = x.get(key + 'Text')
    return t if t is not None else x.get(key)
